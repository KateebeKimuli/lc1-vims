/**
 * createResidentFromBirth(villageId, birthRecord, userId)
 * When a birth is registered, automatically create a resident record
 * for the newborn. This increments the active resident count.
 *
 * @param {string} villageId   - current village
 * @param {object} birthRecord - the saved birth record
 * @param {string} userId      - who performed the action
 * @returns {string} id of the created resident
 */
export async function createResidentFromBirth(villageId, birthRecord, userId) {
  const { v4: uuidv4 } = await import('uuid')
  const db    = await getVillageDB(villageId)
  const now   = new Date().toISOString()
  const resId = uuidv4()

  const residentRecord = {
    id:           resId,
    // FIX: use childSurname (explicitly entered) not birth.surname (didn't exist)
    surname:      birthRecord.childSurname || '',
    firstName:    birthRecord.childName || '',
    otherNames:   '',
    dateOfBirth:  birthRecord.dateOfBirth,
    sex:          birthRecord.sex || '',
    village:      birthRecord.village || '',
    status:       'active',                             // born here = active resident
    residentType: 'permanent',
    motherId:     birthRecord.motherId || '',
    fatherId:     birthRecord.fatherId || '',
    birthId:      birthRecord.id,                       // link back to birth record
    nationality:  'Ugandan',
    createdAt:    now,
    createdBy:    userId,
    syncStatus:   'pending',
    updatedAt:    now,
    source:       'birth_registration',
  }

  await db.add('residents', residentRecord)

  // Mark birth record as having created a resident
  const birth = await db.get('births', birthRecord.id)
  if (birth) {
    await db.put('births', { ...birth, residentCreated: true, residentId: resId })
  }

  await db.add('audit', {
    action: 'CREATE', table: 'residents', recordId: resId, userId,
    details: { source: 'birth_registration', childName: birthRecord.childName },
    timestamp: now
  })

  return resId
}

