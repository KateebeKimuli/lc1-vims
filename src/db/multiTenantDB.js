/**
 * generateResetToken(villageId, username)
 * Master admin generates a one-time reset token for a village official.
 * Token expires in 24 hours. Returns the token string to give to the user.
 */
export async function generateResetToken(villageId, username) {
  const db    = await getMasterDB()
  // Generate a random 8-character token (easy to type/communicate verbally)
  const token = Math.random().toString(36).slice(2, 10).toUpperCase()
  const expiry = new Date(Date.now() + 24 * 60 * 60 * 1000).toISOString()

  await db.put('resetTokens', {
    token,
    villageId,
    username,
    expiresAt: expiry,
    used:      false,
    createdAt: new Date().toISOString()
  })

  await db.add('globalAudit', {
    action: 'RESET_TOKEN_GENERATED',
    villageId,
    details: { username, token, expiresAt: expiry },
    timestamp: new Date().toISOString()
  })

  return token
}

/**
 * verifyAndUseResetToken(token, villageId, username)
 * Validates a reset token. Returns true if valid, false otherwise.
 * Marks the token as used so it cannot be reused.
 */
export async function verifyAndUseResetToken(token, villageId, username) {
  const db  = await getMasterDB()
  const rec = await db.get('resetTokens', token)

  if (!rec)                             return { valid: false, reason: 'Token not found' }
  if (rec.used)                         return { valid: false, reason: 'Token already used' }
  if (rec.villageId !== villageId)      return { valid: false, reason: 'Wrong village' }
  if (rec.username !== username)        return { valid: false, reason: 'Wrong username' }
  if (new Date(rec.expiresAt) < new Date()) return { valid: false, reason: 'Token expired' }

  // Mark as used
  await db.put('resetTokens', { ...rec, used: true, usedAt: new Date().toISOString() })
  return { valid: true }
}

/**
 * resetUserPassword(villageId, username, newPassword)
 * Sets a new password for a village official after token verification.
 */
export async function resetUserPassword(villageId, username, newPassword) {
  const db     = await getVillageDB(villageId)
  const user   = await db.getFromIndex('users', 'username', username)
  if (!user) throw new Error('User not found in this village')
  const hashed = await hashPassword(newPassword)   // always hash before storing
  await db.put('users', { ...user, password: hashed, updatedAt: new Date().toISOString() })
}

