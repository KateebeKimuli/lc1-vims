/**
 * seedMasterAdmin()
 * Creates the master SYSTEM_ADMIN account on first launch.
 * This account can log into any village for maintenance.
 */
export async function seedMasterAdmin() {
  const db    = await getMasterDB()
  const count = await db.count('systemUsers')
  if (count === 0) {
    // Hash the default password before storing
    const hashedPw = await hashPassword('MoLG@Uganda2024')
    await db.add('systemUsers', {
      id:         'master-001',
      username:   'sysadmin',
      password:   hashedPw,   // stored as PBKDF2 hash, never plain text
      role:       'SYSTEM_ADMIN',
      fullName:   'System Administrator',
      userStatus: 'active',
      createdAt:  new Date().toISOString()
    })
  }
}

/**
 * setupVillage(villageProfile)
 * Called when a village is set up for the first time on a device.
 * Creates their Chairperson account and registers the village in the master registry.
 *
 * @param {object} villageProfile - { villageId, villageName, ... }
 * @param {object} chairAccount   - { username, password, fullName }
 */
export async function setupVillage(villageProfile, chairAccount) {
  const masterDB  = await getMasterDB()
  const villageDB = await getVillageDB(villageProfile.villageId)

  // Check if this village already has users — if so, it's already set up
  const existingUsers = await villageDB.count('users')
  if (existingUsers > 0) {
    // Village already set up — do NOT overwrite credentials.
    // Return alreadyExisted flag so the UI can show the right message
    // instead of trying to log in with potentially wrong credentials.
    return { alreadyExisted: true }
  }

  // Register in master village registry (upsert — safe to repeat)
  await masterDB.put('villageRegistry', {
    ...villageProfile,
    setupAt:  new Date().toISOString(),
    isActive: true,
  })

  // Hash password before storing — never store plain text
  const hashedChairPw = await hashPassword(chairAccount.password)
  await villageDB.add('users', {
    id:         `chair-${villageProfile.villageId}`,
    username:   chairAccount.username,
    password:   hashedChairPw,
    role:       'LC1_CHAIR',
    fullName:   chairAccount.fullName,
    userStatus: 'active',
    phone:      chairAccount.phone || '',
    createdAt:  new Date().toISOString()
  })

  // Save the village profile in the village DB settings
  for (const [key, value] of Object.entries(villageProfile)) {
    await villageDB.put('settings', { key, value })
    await villageDB.put('villageProfile', { key, value })
  }

  // Log to global audit
  await masterDB.add('globalAudit', {
    action:    'VILLAGE_SETUP',
    villageId: villageProfile.villageId,
    details:   { villageName: villageProfile.villageName },
    timestamp: new Date().toISOString()
  })

  return { alreadyExisted: false }
}

/**
 * isVillageSetup(villageId)
 * Returns true if this village has already been configured on this device.
 */
export async function isVillageSetup(villageId) {
  try {
    const db  = await getMasterDB()
    const rec = await db.get('villageRegistry', villageId)
    return !!rec
  } catch { return false }
}

