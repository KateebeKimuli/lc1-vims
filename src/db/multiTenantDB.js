/**
 * ============================================================
 * MULTI-TENANT DATABASE — src/db/multiTenantDB.js
 * ============================================================
 * ARCHITECTURE OVERVIEW
 * ─────────────────────
 * This is a NATIONAL SYSTEM. Every village in Uganda uses the
 * same web application but each village's data is completely
 * isolated in its own IndexedDB database:
 *
 *   lc1-master          — System admin DB (one per device)
 *   lc1-village-{id}    — One DB per village (e.g. lc1-village-V024)
 *
 * HOW IT WORKS:
 *   1. On login, the user selects their village.
 *   2. We open the DB named `lc1-village-{villageId}`.
 *   3. ALL reads/writes for that session go to that DB only.
 *   4. A SYSTEM_ADMIN (master) account can open ANY village's DB
 *      for maintenance, password resets, and cross-village checks.
 *
 * CROSS-VILLAGE NIN CHECK:
 *   When registering a resident, we check their NIN against:
 *     a) The current village DB (local, always)
 *     b) All other village DBs on this device (local, best-effort)
 *     c) The central API server (if online)
 *   This prevents a person being registered as an active resident
 *   in two villages simultaneously.
 *
 * RESIDENT STATUS RULES:
 *   - 'active'   → counted in "current residents" stat
 *   - 'deceased' → moved to deceased section, NOT counted in active
 *   - 'migrated' → moved out, NOT counted in active, can register
 *                  as active in a new village
 *   - 'tenant'   → registered here but "home village" is elsewhere
 *                  (NIN can appear active in their home village too)
 *
 * BIRTH → RESIDENT AUTO-CREATION:
 *   When a birth is registered, a new resident record is auto-created
 *   with status='active', incrementing the active resident count.
 * ============================================================
 */

import { openDB } from 'idb'
import { hashPassword } from '../security/crypto.js'

// ── Database name builders ─────────────────────────────────────────────────
const MASTER_DB_NAME  = 'lc1-master'          // system admin + village registry
const villageDBName   = (id) => `lc1-village-${id}`  // per-village data

const DB_VERSION = 1

// ─────────────────────────────────────────────────────────────────────────
// MASTER DATABASE (system admin, village registry, password resets)
// ─────────────────────────────────────────────────────────────────────────

/**
 * getMasterDB()
 * Opens the master database used by the SYSTEM_ADMIN account.
 * Contains: system users, all registered villages, reset tokens, global audit.
 */
export async function getMasterDB() {
  return openDB(MASTER_DB_NAME, DB_VERSION, {
    upgrade(db) {

      // ── SYSTEM USERS ─────────────────────────────────────────────────
      // Stores the master admin account and any super-users.
      if (!db.objectStoreNames.contains('systemUsers')) {
        const u = db.createObjectStore('systemUsers', { keyPath: 'id' })
        u.createIndex('username',   'username',   { unique: true })
        u.createIndex('role',       'role')
      }

      // ── VILLAGE REGISTRY ──────────────────────────────────────────────
      // One record per village that has been set up on this device.
      // Lets us list all villages for the master admin and for cross-village NIN checks.
      if (!db.objectStoreNames.contains('villageRegistry')) {
        const v = db.createObjectStore('villageRegistry', { keyPath: 'villageId' })
        v.createIndex('districtId', 'districtId')
        v.createIndex('setupAt',    'setupAt')
      }

      // ── PASSWORD RESET TOKENS ─────────────────────────────────────────
      // Short-lived tokens generated by master admin for village officials.
      // Token expires after 24 hours.
      if (!db.objectStoreNames.contains('resetTokens')) {
        const t = db.createObjectStore('resetTokens', { keyPath: 'token' })
        t.createIndex('villageId', 'villageId')
        t.createIndex('username',  'username')
        t.createIndex('expiresAt', 'expiresAt')
      }

      // ── GLOBAL AUDIT ──────────────────────────────────────────────────
      // Cross-village operations logged here (password resets, village setups).
      if (!db.objectStoreNames.contains('globalAudit')) {
        const a = db.createObjectStore('globalAudit', { keyPath: 'id', autoIncrement: true })
        a.createIndex('villageId', 'villageId')
        a.createIndex('action',    'action')
        a.createIndex('timestamp', 'timestamp')
      }
    }
  })
}

