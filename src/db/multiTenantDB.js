/**
 * getResidentStats(villageId)
 * Returns accurate population counts split by status.
 * This is the source of truth for the dashboard stat tiles.
 *
 * RULES:
 *   activeCount   = residents WHERE status IN ('active', 'tenant')
 *   deceasedCount = residents WHERE status = 'deceased'
 *   migratedCount = residents WHERE status = 'migrated'
 */
export async function getResidentStats(villageId) {
  const db        = await getVillageDB(villageId)
  const all       = await db.getAll('residents')
  const active    = all.filter(r => r.status === 'active' || r.status === 'tenant')
  const deceased  = all.filter(r => r.status === 'deceased')
  const migrated  = all.filter(r => r.status === 'migrated')
  return {
    total:    all.length,
    active:   active.length,
    deceased: deceased.length,
    migrated: migrated.length,
    tenants:  all.filter(r => r.residentType === 'tenant').length,
    male:     active.filter(r => r.sex === 'Male').length,
    female:   active.filter(r => r.sex === 'Female').length,
  }
}

/**
 * getDashboardStats(villageId)
 * Returns all headline counts for the dashboard.
 */
export async function getDashboardStats(villageId) {
  const db = await getVillageDB(villageId)
  const [households, land, births, deaths, welfare, businesses, security] =
    await Promise.all([
      db.count('households'), db.count('land'),
      db.count('births'),     db.count('deaths'),
      db.count('welfare'),    db.count('businesses'), db.count('security'),
    ])
  const allCases  = await db.getAll('cases')
  const openCases = allCases.filter(c => c.status === 'open').length
  const resStats  = await getResidentStats(villageId)

  return {
    ...resStats,
    residents: resStats.active,  // dashboard "residents" = active only
    households, land, births, deaths,
    cases: allCases.length, openCases,
    welfare, businesses, security,
  }
}

