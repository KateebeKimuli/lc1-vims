// ─────────────────────────────────────────────────────────────────────────
// CROSS-VILLAGE NIN UNIQUENESS CHECK
// ─────────────────────────────────────────────────────────────────────────

/**
 * checkNINAcrossVillages(nin, currentVillageId, excludeResidentId)
 * Checks whether a NIN is already registered in any OTHER village.
 *
 * DECEASED RULE: A deceased person's NIN is PERMANENTLY BLOCKED.
 * Their identity cannot be reused under any circumstances — not as
 * a tenant, not as affiliated, not for any registration reason.
 * This prevents identity fraud using deceased persons' documents.
 *
 * Returns:
 *   { conflict: false }
 *   { conflict: true, villages: [...], deceased: true/false }
 */
export async function checkNINAcrossVillages(nin, currentVillageId, excludeResidentId = null) {
  if (!nin || nin.length < 5) return { conflict: false }

  const villages  = await getRegisteredVillages()
  const conflicts = []

  for (const village of villages) {
    if (village.villageId === currentVillageId) continue
    try {
      const db  = await getVillageDB(village.villageId)
      const all = await db.getAll('residents')
      const found = all.filter(r =>
        r.id !== excludeResidentId &&
        r.nin === nin &&
        // Block if: active, affiliated, migrated, OR deceased
        // Only exclude if explicitly never registered (shouldn't exist if nin matches)
        r.status !== undefined
      )
      if (found.length > 0) {
        conflicts.push({
          villageId:   village.villageId,
          villageName: village.villageName,
          resident:    found[0],
          deceased:    found[0].status === 'deceased',
        })
      }
    } catch { /* village DB not on this device */ }
  }

  return conflicts.length > 0
    ? { conflict: true, villages: conflicts, deceased: conflicts.some(c => c.deceased) }
    : { conflict: false }
}

/**
 * checkNameDOBAcrossVillages(surname, firstName, dateOfBirth, currentVillageId, excludeId)
 * Checks whether a person with the same surname + firstName + dateOfBirth
 * already exists in ANY village on this device.
 *
 * DECEASED RULE: If the matching person is deceased, this is a HARD BLOCK.
 * A deceased person's name and date of birth cannot be registered again
 * regardless of registration reason.
 *
 * Returns:
 *   { conflict: false }
 *   { conflict: true, villages: [...], deceased: true/false }
 */
export async function checkNameDOBAcrossVillages(
  surname, firstName, dateOfBirth, currentVillageId, excludeId = null
) {
  if (!surname || !firstName || !dateOfBirth) return { conflict: false }

  const villages  = await getRegisteredVillages()
  const conflicts = []
  const sl = surname.trim().toLowerCase()
  const fl = firstName.trim().toLowerCase()

  for (const village of villages) {
    if (village.villageId === currentVillageId) continue
    try {
      const db  = await getVillageDB(village.villageId)
      const all = await db.getAll('residents')
      const found = all.filter(r =>
        r.id !== excludeId &&
        r.surname?.trim().toLowerCase()   === sl &&
        r.firstName?.trim().toLowerCase() === fl &&
        r.dateOfBirth === dateOfBirth
        // No status filter — deceased records also block re-registration
      )
      if (found.length > 0) {
        conflicts.push({
          villageId:   village.villageId,
          villageName: village.villageName,
          resident:    found[0],
          deceased:    found[0].status === 'deceased',
        })
      }
    } catch { /* village DB not on this device */ }
  }

  return conflicts.length > 0
    ? { conflict: true, villages: conflicts, deceased: conflicts.some(c => c.deceased) }
    : { conflict: false }
}

